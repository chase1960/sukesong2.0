#!/usr/bin/env bash
# R967-F06 · 5 条短烟测的**执行模板**（**只打勾，不替人验收**）
#
# 计划 §七 + R967-F06 的判据。每条都是「用户做一个操作 → 看到什么」的可观察落点。
# 这条脚本不替人验 —— 它只**把操作步骤**和**断言**写出来，让人照着点、记结果。
#
# 用法：
#   bash scripts/smoke.sh <compose_project> <期望SHA>
#   例：bash scripts/smoke.sh shangshu-local-green 20c5cce5
#
# 报账格式：每条后填  PASS / FAIL / 未验，**缺一类写「无」**（CLAUDE.md 尾注同规矩）。

set -eo pipefail
PROJ="${1:-}"; SHA="${2:-}"
[ -n "$PROJ" ] || { echo "用法: bash $0 <compose_project> [期望SHA]" >&2; exit 1; }

# 抽 5 条烟测的简要操作
# ⚠️ 不要写成 ${SHA:+（期望 $SHA）} —— bash 在展开词里放全角括号会吞字符（已实测，见日志 22:50）。
EXPECT_LABEL=""
if [ -n "$SHA" ]; then EXPECT_LABEL=" (期望 $SHA)"; fi

cat <<NOTE
════════════════════════════════════════════════════════
 R967-F06 · 5 条短烟测 · ${PROJ}${EXPECT_LABEL}
════════════════════════════════════════════════════════
每条 = 准备 / 做 / 断言（看到了就是 PASS，差一点也不写 PASS）。
这是「执行模板」不是「自动化跑」 —— 跑完每条 1-3 分钟人点。

──── 烟测 1 · 普通表输入粘贴，刷新与导出一致 ────────────
准备：普通员工账号（**非管理员**）。
做：  新建一张表 → 键盘输入几格 → 粘贴一段带前导零的文本（"00123"）。
判：  刷新页面后那几格值都在、**前导零不被吞成 123**；导出 XLSX 打开比对一致。
**工具不支持** = 缺带真实 IME / 桌面 Excel 的机器 → 写「工具不支持」，不许写 PASS。
结果：_______________

──── 烟测 2 · 混合表：合法值改进去，非法包要么拒要么零写 ────
准备：一张**既有绑定列又有普通列**的表（晋升过的）。
做：  改一个**合法**绑定值 + 一个普通值，提交；再提交一个**含非法值**的包。
判：  两次提交后，**数据库里的绑定值 / 工作 XLSX / 操作日志**三处对得上；非法那次是**零写**。
**不许**「日志说写了、库里没有」或「改了一半」。
结果：_______________

──── 烟测 3 · 无权被拒、有权不误伤 ────────────
准备：两个普通账号 + 一个管理员；一份共享附件 + 一批未确认候选。
做：  无权账号去**读候选 / 下载附件**；**前端隐藏不算** —— 用直接 API / 链接试。
判：  无权**被拒**（403 或等价拒绝，有拒绝回执）；有权**照常能读能下**，没被误伤。
**前端隐藏不抵扣直接 API 反例**（计划 §五 E 自测）。
结果：_______________

──── 烟测 4 · 含图签名邮件保存重开，共享草稿 From 不变 ──────
准备：带图片的默认签名；一个共享邮箱。
做：  新建草稿（自动带签名）→ 保存 → 关掉 → 重新打开。
判：  ① 草稿**能保存**（不是「默认签名含图即无法保存」）；② 重开后**签名还在、图片还在**；
      ③ 共享草稿重开后 **From 仍是共享邮箱**（没被改成个人）。
**⚠️ 不真实外发** —— 只到保存/重开为止。
对应已知缺陷 BASE967-03。
结果：_______________

──── 烟测 5 · 同一 Assistant：拒绝一个、确认另一个，刷新后正确 ──────
准备：一个 Assistant 会话，让它**分别**生成一个 Excel 候选和一个邮件候选。
做：  **拒绝**其中一个、**确认**另一个 → 刷新 → 回原对话看那轮记录。
判：  ① 两个候选都在、都标明来源动作；② 拒/确各一个；③ 刷新后**被拒的没写进去、被确认的写进去了**（值正确）；
      ④ **原对话**那轮的拒/确状态还在、可恢复（不是被历史覆盖没了）。
⚠️ 未确认候选**仅指定审核人可见** —— 顺手用另一个账号看一眼：**不该看见**。
结果：_______________

